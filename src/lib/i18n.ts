export function translateToBengali(value: string) {
  const trimmed = value.trim();
  const direct = bnSupplement[trimmed] ?? bnCopy[trimmed];
  if (direct) return direct;

  const punctuation = trimmed.match(/[.!?…:]$/)?.[0] ?? '';
  if (punctuation) {
    const withoutPunctuation = trimmed.slice(0, -punctuation.length).trim();
    const translated = bnSupplement[withoutPunctuation] ?? bnCopy[withoutPunctuation];
    if (translated) return `${translated}${punctuation === '.' ? '।' : punctuation}`;
  }

  const numberedLabel = trimmed.match(/^(\d+)\s+(.+)$/);
  if (numberedLabel) {
    const translatedLabel = bnSupplement[numberedLabel[2]] ?? bnCopy[numberedLabel[2]];
    if (translatedLabel) {
      const bengaliNumber = numberedLabel[1].replace(/\d/g, (digit) => '০১২৩৪৫৬৭৮৯'[Number(digit)]);
      return `${bengaliNumber} ${translatedLabel}`;
    }
  }

  const supportCount = trimmed.match(/^(\d+) areas of support$/);
  if (supportCount) {
    const bengaliNumber = supportCount[1].replace(/\d/g, (digit) => '০১২৩৪৫৬৭৮৯'[Number(digit)]);
    return `${bengaliNumber}টি সেবাক্ষেত্র`;
  }

  return null;
}
